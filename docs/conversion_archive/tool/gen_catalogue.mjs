/* Turn the reference's feature registry into the Flutter registry.
 *
 * TEMPORARY CONVERSION TOOLING. Deleted with the prototype at Phase F9; the
 * Dart it writes is production source and stays, hand-maintained from then on.
 *
 *   node docs/conversion_archive/tool/gen_catalogue.mjs
 *
 * §19 names `catalogue.js` the single source of truth for every feature, so
 * the Flutter registry is *generated from it* rather than retyped beside it.
 * Two files are read, because the reference splits one contract across two:
 *
 *   data/catalogue.js    identity, category, gating, interests, keywords
 *   data/tool-specs.js   archetype, source, freshness, Home and quick
 *                        eligibility, related tools
 *
 * Three things are deliberately **not** carried across:
 *
 *   `n` (the display name) is carried as a fallback only. The reference seeds
 *   `f.<id>` into the English dictionary from the catalogue itself, so the
 *   name is already a translated string in Urdu and Arabic; Flutter reads the
 *   ARB and uses this only when a key is missing, which a test forbids.
 *
 *   `m` (the status line) is not a catalogue fact at all — it is a stand-in
 *   for what a tool's own repository will report. It becomes a status *key*
 *   here and a localised string in the ARBs, because the prototype renders it
 *   untranslated in every language (recorded in KNOWN_DIFFERENCES as D22).
 *
 *   `act` is dropped. `eligibility.js` overrides it for every feature —
 *   `actFor()` returns `'tool:' + f.id` unconditionally — so carrying the
 *   field would carry a value nothing reads.
 *
 * Deterministic: same input, same output.
 */
import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

import { LUME } from '../../../assets/js/data/catalogue.js';
import { LUME_SPEC } from '../../../assets/js/data/tool-specs.js';

const OUT = resolve(
  process.cwd(),
  'lib/features/catalogue/data/feature_catalogue.dart',
);

/* The reference names an icon `i-cloud-sun`; LumeIcons keeps the asset's own
   name, `cloud-sun`, so the prefix is all that comes off. */
const icon = (id) => id.replace(/^i-/, '');

const dartString = (s) =>
  "'" + String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/\$/g, '\\\$') + "'";

const dartSet = (xs) =>
  xs.length
    ? '<String>{' + xs.map(dartString).join(', ') + '}'
    : 'const <String>{}';

const lines = [];
const w = (s = '') => lines.push(s);

w('// GENERATED by docs/conversion_archive/tool/gen_catalogue.mjs — do not edit');
w('// by hand while the web reference is still present. Regenerate instead.');
w('//');
w('// Source: assets/js/data/catalogue.js + assets/js/data/tool-specs.js.');
w('// §19 makes that registry the single source of truth for every feature, so');
w('// this file is produced from it rather than maintained alongside it.');
w('//');
w('// After Phase F9 removes the prototype this becomes ordinary source and is');
w('// edited directly; `catalogue_test.dart` is what keeps it honest either way.');
w('library;');
w();
w("import '../domain/lume_feature.dart';");
w();
w('/// Every feature in the product, in catalogue order.');
w('///');
w('/// Order is meaning: the Tools hub renders a category in the order the');
w('/// catalogue declares, so re-sorting this list re-sorts the product.');
w('const List<LumeFeature> kLumeFeatures = <LumeFeature>[');

let sensitiveCount = 0;
let faithCount = 0;

for (const f of LUME.FEATURES) {
  const spec = LUME_SPEC.get(f.id);
  const kw = (f.kw || '')
    .split(/\s+/)
    .filter(Boolean)
    .sort();
  const ints = (f.ints || []).slice();
  if (f.sens) sensitiveCount++;
  if (f.faith) faithCount++;

  const parts = [
    `id: ${dartString(f.id)}`,
    `fallbackName: ${dartString(f.n)}`,
    `icon: ${dartString(icon(f.i))}`,
    `category: LumeToolCategory.${f.c}`,
    `group: LumeFeatureGroup.${f.g === 'islam' ? 'islam' : f.g}`,
  ];
  if (ints.length) parts.push(`interests: ${dartSet(ints)}`);
  if (kw.length) parts.push(`keywords: ${dartSet(kw)}`);
  if (f.faith) parts.push('faith: true');
  if (f.countries) parts.push(`countries: ${dartSet(f.countries.slice().sort())}`);
  if (f.adapts) parts.push('adapts: true');
  if (f.shareable) parts.push('shareable: true');
  if (f.reqCity) parts.push('requiresCity: true');
  if (f.sens) parts.push('sensitive: true');
  if (f.staple) parts.push('staple: true');
  if (f.android) parts.push('androidOnly: true');
  if (spec.homeEligible) parts.push('homeEligible: true');
  if (spec.quickEligible) parts.push('quickEligible: true');
  if (spec.related.length) parts.push(`related: ${dartSet(spec.related)}`);

  w('  LumeFeature(');
  for (const p of parts) w(`    ${p},`);
  w('  ),');
}

w('];');
w();
w('/// The Tools hub\'s category headers, in the order the catalogue declares.');
w('const List<LumeCategory> kLumeCategories = <LumeCategory>[');
for (const c of LUME.CATEGORIES) {
  w('  LumeCategory(');
  w(`    id: LumeToolCategory.${c.id},`);
  w(`    fallbackLabel: ${dartString(c.label)},`);
  w(`    icon: ${dartString(icon(c.icon))},`);
  if (c.faith) w('    faith: true,');
  w('  ),');
}
w('];');
w();

writeFileSync(OUT, lines.join('\n') + '\n');

process.stdout.write(
  `wrote ${LUME.FEATURES.length} features and ${LUME.CATEGORIES.length} ` +
    `categories (${faithCount} faith-gated, ${sensitiveCount} sensitive, ` +
    `${LUME.FEATURES.filter((f) => f.countries).length} country-restricted, ` +
    `${LUME.FEATURES.filter((f) => LUME_SPEC.get(f.id).homeEligible).length} ` +
    `Home-eligible, ${LUME.FEATURES.filter((f) => LUME_SPEC.get(f.id).quickEligible).length} ` +
    `quick-eligible)\n`,
);
